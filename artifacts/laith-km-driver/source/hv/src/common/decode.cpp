UINT32 Decode::InsnLength(const UINT8* p, UINT32 MaxBytes)
{
    UINT32 len = 0;
    bool   opsz   = false;  // 0x66 prefix seen
    bool   addrsz = false;  // 0x67 prefix seen
    bool   rexW   = false;  // REX.W set

    if (!p || MaxBytes == 0)
        return 0;

    // ── Step 1: consume legacy prefixes ─────────────────────────────────────
    while (len < MaxBytes) {
        const UINT8 b = p[len];
        if (b == 0x26 || b == 0x2E || b == 0x36 || b == 0x3E ||
            b == 0x64 || b == 0x65 || b == 0xF0 || b == 0xF2 || b == 0xF3) {
            ++len;
        } else if (b == 0x66) {
            opsz = true; ++len;
        } else if (b == 0x67) {
            addrsz = true; ++len;
        } else {
            break;
        }
    }
    if (len >= MaxBytes) return 0;

    // ── Step 2: optional REX prefix (64-bit mode only) ───────────────────────
    if ((p[len] & 0xF0) == 0x40) {
        if (p[len] & 0x08) rexW = true;
        ++len;
    }
    if (len >= MaxBytes) return 0;

    // ── Step 3: opcode ───────────────────────────────────────────────────────
    UINT8 flags = OF_NONE;
    bool  hasSib = false;

    if (p[len] == 0x0F) {
        ++len;
        if (len >= MaxBytes) return 0;

        if (p[len] == 0x38 || p[len] == 0x3A) {
            // 3-byte opcode
            const bool has_imm8 = (p[len] == 0x3A);
            ++len;
            if (len >= MaxBytes) return 0;
            ++len; // skip 3rd byte
            flags = OF_MODRM | (has_imm8 ? OF_IMM8 : 0);
        } else {
            flags = g_2ByteFlags[p[len]];
            ++len;
        }
    } else {
        flags = g_1ByteFlags[p[len]];
        ++len;
    }

    if (len >= MaxBytes && (flags & (OF_MODRM | OF_IMM8 | OF_IMM16 | OF_IMMF | OF_REL8 | OF_REL32)))
        return 0;

    // ── Step 4: ModRM + SIB + displacement ──────────────────────────────────
    if (flags & OF_MODRM) {
        if (len >= MaxBytes) return 0;
        const UINT8 modrm = p[len++];
        const UINT8 mod   = (modrm >> 6) & 0x3;
        const UINT8 rm    = (modrm     ) & 0x7;

        if (mod != 3) {
            // SIB byte?
            if (rm == 4 && !addrsz) {
                if (len >= MaxBytes) return 0;
                const UINT8 sib = p[len++];
                // SIB: base == 5 with mod==0 → 4-byte disp
                if ((sib & 0x7) == 5 && mod == 0) {
                    len += 4;
                }
            }
            // Displacement
            if (mod == 1) {
                len += 1;
            } else if (mod == 2 || (mod == 0 && rm == 5 && !addrsz)) {
                len += addrsz ? 2 : 4;
            }
        }
    }

    if (len > MaxBytes) return 0;

    // ── Step 5: immediate ────────────────────────────────────────────────────
    if (flags & OF_IMM8)  { len += 1; }
    if (flags & OF_IMM16) { len += 2; }
    if (flags & OF_REL8)  { len += 1; }
    if (flags & OF_REL32) { len += 4; }
    if (flags & OF_IMMF) {
        // 64-bit for REX.W+MOV only, else 32-bit (or 16-bit with opsz)
        if (rexW)       len += 8;
        else if (opsz)  len += 2;
        else            len += 4;
    }
    if (flags & (OF_REL8 | OF_REL32 | OF_IMM8 | OF_IMM16 | OF_IMMF)) {
        if (len > MaxBytes) return 0;
    }

    return len;
}
