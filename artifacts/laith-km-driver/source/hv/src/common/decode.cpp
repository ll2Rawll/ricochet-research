//
// ─── x86-64 instruction-length decoder ───────────────────────────────────────
//
// References:
//   Intel® 64 and IA-32 Architectures Software Developer's Manual,
//   Volume 2 — Instruction Set Reference (Appendix A / B).
//
// We only need to be correct for instructions that could trigger a #NPF
// (i.e. any instruction that touches memory).  The decoder handles:
//   • All legacy prefixes (lock/rep/repne/segment/opsz/addrsz)
//   • REX prefix (0x40..0x4F)
//   • One-, two-, and three-byte opcode maps (0F, 0F 38, 0F 3A)
//   • ModRM + SIB + displacement (0/1/2/4 bytes)
//   • Immediate (0/1/2/4/8 bytes)
//

// Opcode attribute flags (packed into a UINT8 table)
enum OpcodeFlags : UINT8 {
    OF_NONE    = 0x00,
    OF_MODRM   = 0x01,  // has ModRM byte
    OF_IMM8    = 0x02,  // 8-bit immediate
    OF_IMM16   = 0x04,  // 16-bit immediate (ENTER, RET imm16, etc.)
    OF_IMMF    = 0x08,  // full immediate (16/32/64 depending on opsz/REX.W)
    OF_REL8    = 0x10,  // rel8 (Jcc short)
    OF_REL32   = 0x20,  // rel32
    OF_INVALID = 0x80,  // undefined / not handled → decode as 1 byte
};

